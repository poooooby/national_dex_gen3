#!/usr/bin/env python3
"""Generate data/types.lua: the FAIRY type (Gen 6+) for Gen 3.

Gen 3 has 17 types. The battle engine reads its type chart and every species' and
move's type from live tables (src/core/game3/battle/types.lua, Pokemon._types, the move
rows), so src/types.lua adds FAIRY at runtime as type id 18. This tool collects, from
PokeAPI's /type/fairy:

  species  every species whose typing today includes Fairy, by National number, with its
           whole modern typing (the cart's own Clefairy and Gardevoir as well as Togekiss
           and Sylveon), so a Fairy half is never invented or dropped
  forms    the alternate forms tools/form_list.py registers that are Fairy (Galarian
           Weezing, Galarian Rapidash, ...), by form id
  moves    the cart's own moves that became Fairy in Gen 6 (Charm, Sweet Kiss, Moonlight);
           Fairy moves newer than Gen 3 arrive with the new-moves work
  chart    Fairy's matchups, attacking and defending

The species records keep their Gen 3-era typing (build_species.py types_for): that is the
fallback a game gets if src/types.lua cannot install.

    python tools/build_types.py
"""

from __future__ import annotations

import argparse
import concurrent.futures
from pathlib import Path
from typing import Any

import build_species as bs
import form_list

ROOT = Path(__file__).resolve().parent.parent

# PokeAPI damage_relations key -> Gen 3 chart multiplier (tenths)
OFFENSE = {"double_damage_to": 20, "half_damage_to": 5, "no_damage_to": 0}
DEFENSE = {"double_damage_from": 20, "half_damage_from": 5, "no_damage_from": 0}


def collect(api: bs.API, workers: int) -> dict[str, Any]:
    fairy = api.get("/type/fairy")

    def one(entry: dict[str, Any]) -> dict[str, Any]:
        pokemon = api.get(entry["pokemon"]["url"])
        return {
            "name": pokemon["name"],
            "default": bool(pokemon.get("is_default")),
            "dex": int(pokemon["species"]["url"].rstrip("/").rsplit("/", 1)[1]),
            "types": [t["type"]["name"].upper() for t in sorted(pokemon["types"], key=lambda t: t["slot"])],
        }

    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as ex:
        rows = list(ex.map(one, fairy["pokemon"]))

    out: dict[str, Any] = {"species": {}, "forms": {}, "moves": [], "offense": {}, "defense": {}}
    by_name = {r["name"]: r["types"] for r in rows}
    for r in rows:
        if r["default"] and r["dex"] <= bs.LAST_DEX:
            out["species"][r["dex"]] = r["types"]
    # a form takes the typing of the PokeAPI variety it is built from; some forms share
    # their base's default variety (Alcremie's creams, Flabebe's colours)
    for fid, _base, _form, slug in form_list.FORMS:
        if slug in by_name:
            out["forms"][fid] = by_name[slug]
    for move in fairy["moves"]:
        mid = int(move["url"].rstrip("/").rsplit("/", 1)[1])
        if mid <= bs.MAX_MOVE_ID:
            out["moves"].append(bs.engine_id(move["name"]))
    rel = fairy["damage_relations"]
    for key, mult in OFFENSE.items():
        for t in rel[key]:
            out["offense"][t["name"].upper()] = mult
    for key, mult in DEFENSE.items():
        for t in rel[key]:
            out["defense"][t["name"].upper()] = mult
    out["moves"].sort()
    return out


def lua_list(items: list[str]) -> str:
    return "{ " + ", ".join(f'"{s}"' for s in items) + " }"


def write(data: dict[str, Any], path: Path) -> None:
    lines = [
        "-- Generated by tools/build_types.py from PokeAPI /type/fairy. Do not edit by hand.",
        "-- FAIRY for Gen 3: species by National number and forms by id with their whole",
        "-- modern typing, the cart's moves that became Fairy, and Fairy's matchups (tenths:",
        "-- 20 super effective, 5 not very, 0 no effect).",
        "return {",
        "  species = {",
    ]
    for dex in sorted(data["species"]):
        lines.append(f"    [{dex}] = {lua_list(data['species'][dex])},")
    lines.append("  },")
    lines.append("  forms = {")
    for fid in sorted(data["forms"]):
        lines.append(f"    {fid} = {lua_list(data['forms'][fid])},")
    lines.append("  },")
    lines.append(f"  moves = {lua_list(data['moves'])},")
    for side in ("offense", "defense"):
        cells = ", ".join(f"{t} = {m}" for t, m in sorted(data[side].items()))
        lines.append(f"  {side} = {{ {cells} }},")
    lines.append("}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cache", type=Path, default=ROOT / "tools" / ".cache")
    p.add_argument("--refresh", action="store_true")
    p.add_argument("--workers", type=int, default=8)
    p.add_argument("--out", type=Path, default=ROOT / "data" / "types.lua")
    args = p.parse_args()
    data = collect(bs.API(args.cache, args.refresh), args.workers)
    write(data, args.out)
    print(f"{len(data['species'])} species, {len(data['forms'])} forms, {len(data['moves'])} cart moves "
          f"({', '.join(data['moves'])}) -> {args.out}")


if __name__ == "__main__":
    main()
