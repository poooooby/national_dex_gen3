LAST_DEX = 1025
SHARD_SIZE = 100
SHOWDOWN_COMMIT = "965a535ef892d13cd68cf75c076db26f9f32842a"
SHOWDOWN_RAW = "https://raw.githubusercontent.com/smogon/pokemon-showdown/{commit}/data/{name}.ts"

HEADER = ("-- Generated by tools/build_api.py from PokéAPI and Pokémon Showdown (MIT). Do not edit\n"
          "-- by hand; rerun the tool instead.\n")

STAT_KEYS = {"hp": "hp", "attack": "attack", "defense": "defense", "special-attack": "spAttack",
             "special-defense": "spDefense", "speed": "speed"}


def strip_id(text: str) -> str:
    """Upper case, letters and digits only: "King's Rock" -> KINGSROCK, "Flabébé" -> FLABB."""
    return re.sub(r"[^A-Z0-9]", "", text.upper())


def ascii_name(text: str) -> str:
    """A display name in plain ASCII (a battle mod stores it and strips it back to the id)."""
    import unicodedata
    text = text.replace("’", "'").replace("‘", "'")
    return unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")


def english(entries: list[dict[str, Any]], key: str) -> str | None:
    for e in entries or []:
        if e.get("language", {}).get("name") == "en":
            return e.get(key)
    return None


def clean(text: str | None) -> str:
    if not text:
        return ""
    return re.sub(r"\s+", " ", text.replace("­", "")).strip()


def gen_number(name: str | None) -> int | None:
    roman = {"i": 1, "ii": 2, "iii": 3, "iv": 4, "v": 5, "vi": 6, "vii": 7, "viii": 8, "ix": 9}
    if not name:
        return None
    return roman.get(name.split("-", 1)[-1])


# ---------------------------------------------------------------- Showdown

def showdown_file(cache: Path, name: str) -> str:
    path = cache / "showdown" / SHOWDOWN_COMMIT[:8] / f"{name}.ts"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        url = SHOWDOWN_RAW.format(commit=SHOWDOWN_COMMIT, name=name)
        req = urllib.request.Request(url, headers={"User-Agent": "national_dex_gen3-builder/1.0"})
        with urllib.request.urlopen(req, timeout=60) as r:
            path.write_bytes(r.read())
    return path.read_text(encoding="utf-8")


def showdown_blocks(text: str) -> dict[str, list[str]]:
    """Top-level entries of a Showdown data table: id -> its lines (two tabs in)."""
    out: dict[str, list[str]] = {}
    current = None
    for line in text.splitlines():
        m = re.match(r'^\t"?([a-z0-9]+)"?: \{$', line)
        if m:
            current = m.group(1)
            out[current] = []
            continue
        if line == "\t}," or line == "\t}":
            current = None
            continue
        if current is not None:
            out[current].append(line)
    return out


def js_value(text: str) -> Any:
    """A JS literal (numbers, strings, booleans, arrays, plain objects) as Python."""
    t = text.strip().rstrip(",")
    t = re.sub(r"'([^'\\]*)'", lambda m: json.dumps(m.group(1)), t)
    t = re.sub(r'([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:', r'\1"\2":', t)
    t = re.sub(r",\s*([}\]])", r"\1", t)
    return json.loads(t)


def block_fields(lines: list[str], wanted: set[str]) -> dict[str, Any]:
    """The wanted two-tab fields of a block whose value is a literal (one line or a
    multi-line object / array); functions and anything unparsable are skipped."""
    out: dict[str, Any] = {}
    i = 0
    while i < len(lines):
        m = re.match(r"^\t\t([A-Za-z_]+): (.*)$", lines[i])
        if not m or m.group(1) not in wanted:
            i += 1
            continue
        key, rest = m.group(1), m.group(2)
        text = rest
        if rest.rstrip(",") in ("{", "["):
            j = i + 1
            while j < len(lines) and not re.match(r"^\t\t[}\]],?$", lines[j]):
                text += "\n" + lines[j]
                j += 1
            if j < len(lines):
                text += "\n" + lines[j].strip()
            i = j
        try:
            out[key] = js_value(text)
        except (json.JSONDecodeError, ValueError):
            pass
        i += 1
    return out


def showdown_move_flags(cache: Path) -> dict[int, list[str]]:
    flags: dict[int, list[str]] = {}
    for _, lines in showdown_blocks(showdown_file(cache, "moves")).items():
        f = block_fields(lines, {"num", "flags", "isNonstandard"})
        num = f.get("num")
        if not isinstance(num, int) or num <= 0 or f.get("isNonstandard") == "CAP":
            continue
        if num in flags:            # a Z / Max variant sharing the number: keep the first
            continue
        flags[num] = sorted((f.get("flags") or {}).keys())
    return flags


ITEM_FACTS = {"num", "name", "fling", "naturalGift", "isBerry", "isPokeball", "isGem", "isChoice",
              "megaStone", "megaEvolves", "onPlate", "onMemory", "onDrive", "itemUser", "boosts",
              "forcedForme", "zMove", "zMoveType", "zMoveFrom", "ignoreKlutz", "gen"}


def showdown_item_facts(cache: Path) -> dict[str, dict[str, Any]]:
    out = {}
    for sid, lines in showdown_blocks(showdown_file(cache, "items")).items():
        f = block_fields(lines, ITEM_FACTS | {"isNonstandard"})
        if f.get("isNonstandard") == "CAP" or not f.get("name"):
            continue
        f.pop("isNonstandard", None)
        out[sid.upper()] = f
    return out


# ---------------------------------------------------------------- moves

def build_moves(api: bs.API, workers: int, cache: Path) -> list[dict[str, Any]]:
    listing = api.get("/move?limit=3000")["results"]
    ids = sorted(bs.id_from_url(r["url"]) for r in listing if bs.id_from_url(r["url"]) < 10000)
    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as ex:
        moves = list(ex.map(lambda i: api.get(f"/move/{i}"), ids))
    flags = showdown_move_flags(cache)
    out = []
    for m in moves:
        meta = m.get("meta") or {}
        name = ascii_name(english(m["names"], "name") or m["name"])
        chance = m.get("effect_chance")
        short = clean(english(m.get("effect_entries"), "short_effect"))
        long = clean(english(m.get("effect_entries"), "effect"))
        if chance is not None:
            short = short.replace("$effect_chance", str(chance))
            long = long.replace("$effect_chance", str(chance))
        rec: dict[str, Any] = {
            "n": m["id"], "slug": m["name"], "name": name, "strippedId": strip_id(name),
            "type": m["type"]["name"].upper(), "damageClass": m["damage_class"]["name"],
            "pp": m.get("pp") or 0, "priority": m.get("priority") or 0,
            "target": m["target"]["name"], "generation": gen_number(m["generation"]["name"]),
        }
        if m.get("power") is not None:
            rec["power"] = m["power"]
        if m.get("accuracy") is not None:
            rec["accuracy"] = m["accuracy"]
        if chance is not None:
            rec["effectChance"] = chance
        ailment = (meta.get("ailment") or {}).get("name")
        if ailment and ailment != "none":
            rec["ailment"] = ailment
        if meta.get("category"):
            rec["category"] = meta["category"]["name"]
        for src, dst in (("ailment_chance", "ailmentChance"), ("drain", "drain"), ("healing", "healing"),
                         ("crit_rate", "critRate"), ("flinch_chance", "flinchChance"),
                         ("stat_chance", "statChance"), ("min_hits", "minHits"), ("max_hits", "maxHits"),
                         ("min_turns", "minTurns"), ("max_turns", "maxTurns")):
            v = meta.get(src)
            if v:
                rec[dst] = v
        changes = [{"stat": c["stat"]["name"], "change": c["change"]} for c in m.get("stat_changes") or []]
        if changes:
            rec["statChanges"] = changes
        if short:
            rec["shortEffect"] = short
        if long and long != short:
            rec["effect"] = long
        if flags.get(m["id"]) is not None:
            rec["flags"] = flags[m["id"]]
        out.append(rec)
    return out


# ---------------------------------------------------------------- abilities

def build_abilities(api: bs.API, workers: int) -> list[dict[str, Any]]:
    try:
        import ability_behaviour as ab
        behaviour = ab.BEHAVIOUR
    except ImportError:
        behaviour = {}
    listing = api.get("/ability?limit=3000")["results"]
    ids = sorted(bs.id_from_url(r["url"]) for r in listing if bs.id_from_url(r["url"]) < 10000)
    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as ex:
        rows = [a for a in ex.map(lambda i: api.get(f"/ability/{i}"), ids) if a.get("is_main_series")]
    names = {}
    for a in rows:
        names[a["name"]] = ascii_name(english(a["names"], "name") or a["name"].replace("-", " ").title())
    # two abilities with one English name (As One for Glastrier and for Spectrier) are told apart
    # by the rest of their slug, so each keeps an id of its own
    seen: dict[str, list[str]] = {}
    for slug, name in names.items():
        seen.setdefault(name, []).append(slug)
    for name, slugs in seen.items():
        if len(slugs) > 1:
            for slug in slugs:
                extra = slug.split("-")[-1].title()
                names[slug] = f"{name} ({extra})"
    out = []
    for a in rows:
        name = names[a["name"]]
        aid = strip_id(name)
        rec: dict[str, Any] = {
            "id": aid, "n": a["id"], "slug": a["name"], "name": name,
            "generation": gen_number(a["generation"]["name"]),
            "shortEffect": clean(english(a.get("effect_entries"), "short_effect")),
            "effect": clean(english(a.get("effect_entries"), "effect")),
            "species": len(a.get("pokemon") or []),
        }
        changes = []
        for c in a.get("effect_changes") or []:
            text = clean(english(c.get("effect_entries"), "effect"))
            if text:
                changes.append({"generation": gen_number(c["version_group"]["name"]) or
                                _vg_generation(api, c["version_group"]["url"]), "text": text})
        if changes:
            rec["effectChanges"] = changes
        b = behaviour.get(aid)
        if b is not None:
            rec["behaviour"] = b["behaviour"]
            rec["expressible"] = b.get("expressible", True)
            if b.get("notes"):
                rec["notes"] = b["notes"]
        else:
            rec["expressible"] = False
        out.append(rec)
    unknown = sorted(set(behaviour) - {r["id"] for r in out})
    if unknown:
        raise SystemExit("tools/ability_behaviour.py names abilities PokéAPI does not have: "
                         + ", ".join(unknown))
    return out, names


def _vg_generation(api: bs.API, url: str) -> int | None:
    return gen_number(api.get(url)["generation"]["name"])


# ---------------------------------------------------------------- items

def build_items(api: bs.API, workers: int) -> list[dict[str, Any]]:
    listing = api.get("/item?limit=5000")["results"]
    ids = sorted(bs.id_from_url(r["url"]) for r in listing)
    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as ex:
        items = list(ex.map(lambda i: api.get(f"/item/{i}"), ids))
    out, taken = [], set()
    for it in items:
        name = english(it["names"], "name") or it["name"].replace("-", " ").title()
        iid = strip_id(it["name"].replace("-", ""))
        if iid in taken:
            continue
        taken.add(iid)
        rec: dict[str, Any] = {"id": iid, "n": it["id"], "slug": it["name"], "name": name,
                               "category": it["category"]["name"]}
        attrs = sorted(a["name"] for a in it.get("attributes") or [])
        if attrs:
            rec["attributes"] = attrs
        if it.get("fling_power"):
            rec["flingPower"] = it["fling_power"]
        if it.get("fling_effect"):
            rec["flingEffect"] = it["fling_effect"]["name"]
        if it.get("cost"):
            rec["cost"] = it["cost"]
        short = clean(english(it.get("effect_entries"), "short_effect"))
        long = clean(english(it.get("effect_entries"), "effect"))
        rec["shortEffect"] = short
        if long and long != short:
            rec["effect"] = long
        out.append(rec)
    return out


# ---------------------------------------------------------------- species

def detail_method(d: dict[str, Any], names: dict[int, str]) -> dict[str, Any]:
    m: dict[str, Any] = {"trigger": d["trigger"]["name"]}

    def slug(key: str) -> str | None:
        v = d.get(key)
        return v["name"] if isinstance(v, dict) else None

    if d.get("min_level"):
        m["level"] = d["min_level"]
    for src, dst in (("item", "item"), ("held_item", "heldItem"), ("known_move", "knownMove"),
                     ("known_move_type", "knownMoveType"), ("location", "location"),
                     ("trade_species", "tradeSpecies"), ("party_species", "partySpecies"),
                     ("party_type", "partyType")):
        v = slug(src)
        if v:
            m[dst] = v
    for src, dst in (("min_happiness", "minHappiness"), ("min_affection", "minAffection"),
                     ("min_beauty", "minBeauty"), ("gender", "gender"),
                     ("relative_physical_stats", "relativePhysicalStats")):
        if d.get(src) is not None:
            m[dst] = d[src]
    if d.get("time_of_day"):
        m["timeOfDay"] = d["time_of_day"]
    if d.get("needs_overworld_rain"):
        m["needsOverworldRain"] = True
    if d.get("turn_upside_down"):
        m["turnUpsideDown"] = True
    m["text"] = method_text(m)
    return m


def _pretty(slug: str) -> str:
    return slug.replace("-", " ").title()


def method_text(m: dict[str, Any]) -> str:
    t = m["trigger"]
    if t == "level-up":
        text = f"Level {m['level']}" if m.get("level") else "Level up"
    elif t == "use-item":
        text = f"Use {_pretty(m['item'])}" if m.get("item") else "Use an item"
    elif t == "trade":
        text = "Trade"
    else:
        text = _pretty(t)
    extra = []
    if m.get("heldItem"):
        extra.append(f"holding {_pretty(m['heldItem'])}")
    if m.get("tradeSpecies"):
        extra.append(f"for {_pretty(m['tradeSpecies'])}")
    if m.get("minHappiness"):
        extra.append("with high friendship")
    if m.get("minAffection"):
        extra.append("with high affection")
    if m.get("minBeauty"):
        extra.append("with high beauty")
    if m.get("knownMove"):
        extra.append(f"knowing {_pretty(m['knownMove'])}")
    if m.get("knownMoveType"):
        extra.append(f"knowing a {_pretty(m['knownMoveType'])}-type move")
    if m.get("partySpecies"):
        extra.append(f"with {_pretty(m['partySpecies'])} in the party")
    if m.get("partyType"):
        extra.append(f"with a {_pretty(m['partyType'])}-type in the party")
    if m.get("location"):
        extra.append(f"at {_pretty(m['location'])}")
    if m.get("gender") is not None:
        extra.append("(female)" if m["gender"] == 1 else "(male)")
    if m.get("timeOfDay"):
        extra.append(f"({m['timeOfDay']})")
    if m.get("needsOverworldRain"):
        extra.append("in the rain")
    if m.get("turnUpsideDown"):
        extra.append("holding the console upside down")
    rel = m.get("relativePhysicalStats")
    if rel is not None:
        extra.append({1: "(Attack > Defense)", -1: "(Attack < Defense)", 0: "(Attack = Defense)"}[rel])
    return " ".join([text] + extra)


def moves_by_method(pokemon: dict[str, Any]) -> dict[str, list[int]]:
    out: dict[str, set[int]] = {"machine": set(), "tutor": set(), "egg": set(), "other": set()}
    for move in pokemon["moves"]:
        n = bs.id_from_url(move["move"]["url"])
        if n >= 10000:
            continue
        for detail in move["version_group_details"]:
            method = detail["move_learn_method"]["name"]
            if method == "level-up":
                continue
            out[method if method in out else "other"].add(n)
    return {k: sorted(v) for k, v in out.items() if v}


def species_extra(species: dict[str, Any], pokemon: dict[str, Any], ability_names: dict[str, str]
                  ) -> dict[str, Any]:
    rec: dict[str, Any] = {}
    abilities = []
    for a in sorted(pokemon["abilities"], key=lambda a: a["slot"]):
        abilities.append({"name": ability_names.get(a["ability"]["name"], _pretty(a["ability"]["name"])),
                          "slot": a["slot"], "hidden": a["is_hidden"]})
    rec["abilities"] = abilities
    stats, ev = {}, {}
    for s in pokemon["stats"]:
        key = STAT_KEYS[s["stat"]["name"]]
        stats[key] = s["base_stat"]
        if s.get("effort"):
            ev[key] = s["effort"]
    rec["stats"] = stats
    rec["evYield"] = ev
    rec["movesFull"] = [[lv, n] for lv, n in bs.modern_learnset(pokemon) if n < 10000]
    rec["movesByMethod"] = moves_by_method(pokemon)
    rec["eggGroups"] = [g["name"] for g in species.get("egg_groups") or []]
    if species.get("base_happiness") is not None:
        rec["baseHappiness"] = species["base_happiness"]
    rec["genderRate"] = species.get("gender_rate", -1)
    if species.get("growth_rate"):
        rec["growthRateName"] = species["growth_rate"]["name"]
    if species.get("hatch_counter") is not None:
        rec["hatchCounter"] = species["hatch_counter"]
    rec["baseExperience"] = pokemon.get("base_experience")
    if rec["baseExperience"] is None:
        del rec["baseExperience"]
    return rec


def walk_chain(chain: dict[str, Any]) -> tuple[list[int], dict[int, dict[str, Any]]]:
    order: list[int] = []
    parents: dict[int, dict[str, Any]] = {}
    queue = [(chain["chain"], None)]
    while queue:
        node, parent = queue.pop(0)
        dex = bs.id_from_url(node["species"]["url"])
        order.append(dex)
        if parent is not None:
            parents[dex] = {"dex": parent, "details": node.get("evolution_details") or []}
        for child in node.get("evolves_to") or []:
            queue.append((child, dex))
    return order, parents


def build_species(api: bs.API, workers: int, ability_names: dict[str, str]
                  ) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[int, list[int]]]:
    def fetch(dex: int) -> dict[str, Any]:
        species = api.get(f"/pokemon-species/{dex}")
        default = next(v for v in species["varieties"] if v["is_default"])
        pokemon = api.get(default["pokemon"]["url"])
        chain = api.get(species["evolution_chain"]["url"]) if species.get("evolution_chain") else None
        return {"dex": dex, "species": species, "pokemon": pokemon, "chain": chain}

    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as ex:
        fetched = list(ex.map(fetch, range(1, LAST_DEX + 1)))
    chains: dict[int, list[int]] = {}
    parents: dict[int, dict[str, Any]] = {}
    chain_of: dict[int, int] = {}
    for item in fetched:
        if not item["chain"]:
            continue
        cid = item["chain"]["id"]
        if cid not in chains:
            order, ps = walk_chain(item["chain"])
            chains[cid] = order
            parents.update(ps)
        chain_of[item["dex"]] = cid
    records = []
    for item in fetched:
        dex = item["dex"]
        rec = {"dex": dex}
        rec.update(species_extra(item["species"], item["pokemon"], ability_names))
        if dex in chain_of:
            rec["chainId"] = chain_of[dex]
        p = parents.get(dex)
        if p:
            rec["evolvesFrom"] = {"dex": p["dex"],
                                  "methods": [detail_method(d, {}) for d in p["details"]]}
        records.append(rec)

    forms = []
    for fid, base, form, slug in form_list.FORMS:
        try:
            species_slug = base.lower().replace("_", "-")
            species = api.get(f"/pokemon-species/{species_slug}")
        except RuntimeError:
            species = next(i["species"] for i in fetched if bs.engine_id(i["species"]["name"]) == base)
        variety = next((v for v in species["varieties"] if v["pokemon"]["name"] == slug), None)
        if variety is None:
            continue
        pokemon = api.get(variety["pokemon"]["url"])
        rec = {"id": fid, "dex": species["id"], "form": form, "baseSpecies": base}
        rec.update(species_extra(species, pokemon, ability_names))
        forms.append(rec)
    return records, forms, chains


# ---------------------------------------------------------------- output

def write(out: Path, moves, abilities, items, item_flags, records, forms, chains) -> None:
    lua = bs.lua
    (out / "species").mkdir(parents=True, exist_ok=True)
    for old in list(out.glob("*.lua")) + list((out / "species").glob("*.lua")):
        old.unlink()

    def listing(path: Path, comment: str, rows: list[Any]) -> None:
        body = ",\n".join("  " + lua(r) for r in rows)
        path.write_text(HEADER + comment + "return {\n" + body + (",\n" if body else "") + "}\n",
                        encoding="utf-8")

    listing(out / "moves.lua", "-- Every main-series move by National number (n).\n", moves)
    listing(out / "abilities.lua", "-- Every main-series ability; `behaviour` from tools/ability_behaviour.py.\n",
            abilities)
    listing(out / "items.lua", "-- Every PokéAPI item, by id.\n", items)
    (out / "item_flags.lua").write_text(
        HEADER + "-- Showdown's item facts by Showdown id (upper case).\nreturn "
        + lua(dict(sorted(item_flags.items()))) + "\n", encoding="utf-8")
    shards = []
    for n, start in enumerate(range(0, len(records), SHARD_SIZE), 1):
        name = f"{n:03d}.lua"
        shards.append({"file": name, "first": records[start]["dex"],
                       "last": records[min(start + SHARD_SIZE, len(records)) - 1]["dex"]})
        listing(out / "species" / name, "", records[start:start + SHARD_SIZE])
    (out / "species" / "index.lua").write_text(HEADER + "return " + lua(shards) + "\n", encoding="utf-8")
    listing(out / "forms.lua", "-- The forms of tools/form_list.py, by id.\n", forms)
    (out / "chains.lua").write_text(
        HEADER + "-- PokéAPI's evolution chains: chain id -> dex numbers, root first.\nreturn {\n"
        + "".join(f"  [{cid}] = {lua(order)},\n" for cid, order in sorted(chains.items())) + "}\n",
        encoding="utf-8")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--cache", type=Path, default=ROOT / "tools" / ".cache")
    p.add_argument("--out", type=Path, default=ROOT / "data" / "gen12" / "api")
    p.add_argument("--workers", type=int, default=8)
    p.add_argument("--refresh", action="store_true")
    args = p.parse_args()
    api = bs.API(args.cache, args.refresh)
    moves = build_moves(api, args.workers, args.cache)
    abilities, ability_names = build_abilities(api, args.workers)
    items = build_items(api, args.workers)
    item_flags = showdown_item_facts(args.cache)
    records, forms, chains = build_species(api, args.workers, ability_names)
    write(args.out, moves, abilities, items, item_flags, records, forms, chains)
    with_b = sum(1 for a in abilities if "behaviour" in a)
    print(f"{len(moves)} moves ({sum(1 for m in moves if 'flags' in m)} with flags), "
          f"{len(abilities)} abilities ({with_b} with behaviour), {len(items)} items, "
          f"{len(item_flags)} item facts, {len(records)} species, {len(forms)} forms, "
          f"{len(chains)} chains -> {args.out}")


if __name__ == "__main__":
    main()
