#!/usr/bin/env python3
"""
Build the reference data behind WoobleDex's read API on Gen 1 / Gen 2 (data/gen12/api/):
the calls a battle or stats mod makes (moveById, moveFlags, abilityById, itemById, itemFlags,
statsBySpecies, evolutionsOf), answered from PokéAPI and Pokémon Showdown's data (MIT).
src/gen12/dex_api.lua reads it lazily; nothing here is registered with the engine.

  moves.lua       every main-series move by National number: PokéAPI's type, power, accuracy,
                  pp, priority, damage class, target, meta (ailment, drain, healing, crit, hits,
                  flinch, stat chance, category), stat changes, English name and effect text, and
                  Showdown's move flags (contact, sound, punch, ...).
  abilities.lua   every main-series ability by id (upper case, letters and digits: VITALSPIRIT):
                  name, generation, effect text, the per-generation changes, and a `behaviour`
                  block written by hand in tools/ability_behaviour.py (trigger, scope, chance,
                  effects) with `expressible`.
  items.lua       every PokéAPI item by id (upper case, letters and digits: KINGSROCK): name,
                  category, attributes, fling power and effect, cost, effect text.
  item_flags.lua  Showdown's item facts (fling, natural gift, berry, ball, plate / memory /
                  drive type, holder species, boosts, Mega Stone, Z-Crystal) by Showdown id.
  species/NNN.lua by dex number (1-1025): abilities, EV yield, modern base stats, breeding
                  numbers, the newest level-up list in full and the machine / tutor / egg /
                  other moves (as move numbers), the evolution chain and what evolves it.
  forms.lua       the same for each form of tools/form_list.py, by form id.
  chains.lua      each PokéAPI evolution chain, root first, as dex numbers.

Usage:
    python tools/build_api.py
    python tools/build_api.py --cache tools/.cache --workers 8
"""

