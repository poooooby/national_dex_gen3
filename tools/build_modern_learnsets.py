#!/usr/bin/env python3
"""The newer moves the original 386 Pokemon learn in the modern games (the "Modern Moves"
option, on by default).

For each of National Dex #1-386: the level-up moves of the newest main-series game that lists
the species (the same choice as tools/build_species.py) that Gen 3 has (its own 1-354) or that are
real moves here (data/moves.lua), at their modern level, and the newer egg moves that are real
moves. The species' own Gen 3 learnset is left as it is; while the option is on,
src/modern_learnsets.lua adds these rows to it, and a move the cart teaches later than today's
level is learned at today's level instead (Squirtle's Water Gun at 3, not 13).

    python tools/build_modern_learnsets.py      # PokeAPI responses cached in tools/.cache

Writes data/species/modern.lua.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_species as BS  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
LAST_CART_DEX = 386


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cache", type=Path, default=ROOT / "tools" / ".cache")
    ap.add_argument("--out", type=Path, default=ROOT / "data" / "species" / "modern.lua")
    ap.add_argument("--workers", type=int, default=8)
    a = ap.parse_args()

    api = BS.API(a.cache)
    real = BS.real_moves()                         # PokeAPI move id -> this mod's index (355+)
    if not real:
        sys.exit("data/moves.lua has no real moves; run tools/build_moves.py first")

    def fetch(dex: int):
        species = api.get(f"/pokemon-species/{dex}")
        default = next(v for v in species["varieties"] if v["is_default"])
        return dex, api.get(default["pokemon"]["url"])

    with concurrent.futures.ThreadPoolExecutor(max_workers=a.workers) as ex:
        fetched = list(ex.map(fetch, range(1, LAST_CART_DEX + 1)))

    out, rows_total, eggs_total = {}, 0, 0
    for dex, pokemon in fetched:
        rows = sorted({(level, mid if mid <= BS.MAX_MOVE_ID else real[mid])
                       for level, mid in BS.modern_learnset(pokemon) if mid <= BS.MAX_MOVE_ID or mid in real})
        eggs = sorted({real[BS.id_from_url(m["move"]["url"])] for m in pokemon["moves"]
                       if BS.id_from_url(m["move"]["url"]) in real
                       and any(d["move_learn_method"]["name"] == "egg" for d in m["version_group_details"])})
        if rows or eggs:
            out[dex] = (rows, eggs)
            rows_total += len(rows)
            eggs_total += len(eggs)

    L = [
        "-- Generated by tools/build_modern_learnsets.py. Do not edit by hand.",
        "-- The level-up moves the original 386 learn in the modern games (Gen 3's own moves and this",
        "-- mod's real moves, data/moves.lua), by National number: rows { level, move }, plus their",
        "-- newer egg moves. Merged into the cart's own learnsets while the Modern Moves option is on",
        "-- (src/modern_learnsets.lua): each move at the earlier of the cart's level and today's.",
        "return {",
    ]
    for dex in sorted(out):
        rows, eggs = out[dex]
        parts = []
        if rows:
            parts.append("learnset = { " + ", ".join(f"{{ {lv}, {mv} }}" for lv, mv in rows) + " }")
        if eggs:
            parts.append("eggMoves = { " + ", ".join(str(m) for m in eggs) + " }")
        L.append(f"  [{dex}] = {{ " + ", ".join(parts) + " },")
    L += ["}", ""]
    a.out.write_text("\n".join(L), encoding="utf-8", newline="\n")
    print(f"{len(out)} of {LAST_CART_DEX} species have modern rows: {rows_total} level-up rows, "
          f"{eggs_total} egg moves -> {a.out}")


if __name__ == "__main__":
    main()
