"""Writes data/art_heights.lua: how tall each WoobleSprite front picture really stands, in metres,
for other mods' height charts (WoobleOS's Pokedex). Read through mod.exports.artHeightOf /
artHeights (src/art_heights.lua).

Source: poke-scale-realism's data/scale.json (the measured dataset whose `height` factors are in
g9-battle-sprites-gen3's data/sprite_scale.lua, what WoobleView sizes battles by). Rerun after
that dataset is rebuilt:

    python tools/build_art_heights.py [path/to/scale.json]

Per sprite id (species ids as in the pack: ONIX, VULPIX_ALOLA, MEOWSTIC_FEMALE):
  dex       National Dex number (a form's is its base's)
  slot      the engine slot (forms 1090+; nil for a female sheet)
  pokedex   the Pokedex height, m (PokeAPI's own for forms: Alolan Exeggutor 10.9)
  standing  the resting picture, feet to top, m: how tall it is drawn standing still
  art       feet to the top of the art over the whole animation, m (a leap counts; what
            WoobleView's Battle Fit sizes battles by)
  width     the resting picture's width, m
  long      true when the Pokedex number is a length (serpents, fish), so standing < pokedex
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT = ROOT.parent / "poke-scale-realism" / "data" / "scale.json"
OUT = ROOT / "data" / "art_heights.lua"


def num(v: float) -> str:
    return f"{v:.3f}".rstrip("0").rstrip(".") if v else "0"


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    data = json.loads(src.read_text(encoding="utf-8"))
    rows = []
    for r in sorted(data["species"], key=lambda r: (r["dex"], r["id"])):
        m = r["measure"]
        ppm = r["ppm"]
        standing = (m["feet_row"] - m["bbox"][1]) / ppm
        api = r.get("pokeapi") or {}
        fields = [f"dex = {r['dex']}"]
        if r.get("slot") is not None:
            fields.append(f"slot = {r['slot']}")
        fields += [
            f"pokedex = {num(api.get('height_m', r['pack_ht_m']))}",
            f"standing = {num(standing)}",
            f"art = {num(m['art_h_px'] / ppm)}",
            f"width = {num(r['width_m'])}",
        ]
        if r["mode"] == "length":
            fields.append("long = true")
        rows.append(f"  {r['id']} = {{ {', '.join(fields)} }},")
    meta = data.get("meta", {})
    out = [
        "-- Generated by tools/build_art_heights.py from poke-scale-realism's data/scale.json. Do not",
        "-- edit by hand; rerun the tool. How tall each WoobleSprite front picture really stands, in",
        "-- metres (src/art_heights.lua serves it as mod.exports.artHeightOf / artHeights):",
        "--   pokedex   the Pokedex height     standing  the resting picture, feet to top",
        "--   art       feet to the top over the whole animation (WoobleView's battle size)",
        "--   width     the resting picture's width     long  the Pokedex number is a length",
        f"-- Dataset {meta.get('generated', '?')}, PokeAPI {str(meta.get('pokeapi_commit', '?'))[:10]}.",
        "return {",
        *rows,
        "}",
    ]
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} sprites from {src}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
