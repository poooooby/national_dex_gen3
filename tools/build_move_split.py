"""Writes data/move_split.lua: every damaging move's class in today's games (physical or
special), by its Gen 3 move index, for the Move Split option on FireRed to Emerald
(src/move_split.lua).

Sources, both already in the repo:
  data/gen12/api/moves.lua  every main-series move by National number with PokeAPI's damage class
                            (tools/build_api.py)
  data/moves.lua            this mod's newer moves: Gen 3 index (355+) and National number (`api`)
The cart's own moves 1-354 are their National numbers. Status moves are left out.

    python tools/build_move_split.py
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API = ROOT / "data" / "gen12" / "api" / "moves.lua"
OURS = ROOT / "data" / "moves.lua"
OUT = ROOT / "data" / "move_split.lua"


def main() -> int:
    cls = {}
    for line in API.read_text(encoding="utf-8").splitlines():
        m = re.search(r"\bn = (\d+),.*?\bdamageClass = \"(\w+)\"", line)
        if m:
            cls[int(m.group(1))] = m.group(2)
    if len(cls) < 900:
        raise SystemExit(f"only {len(cls)} moves read from {API}")
    rows = {}
    for n in range(1, 355):
        c = cls.get(n)
        if c in ("physical", "special"):
            rows[n] = c[0]
    ours = 0
    for line in OURS.read_text(encoding="utf-8").splitlines():
        m = re.search(r"\bindex = (\d+), api = (\d+)", line)
        if not m:
            continue
        c = cls.get(int(m.group(2)))
        if c in ("physical", "special"):
            rows[int(m.group(1))] = c[0]
            ours += 1
    out = [
        "-- Generated by tools/build_move_split.py. Do not edit by hand; rerun the tool instead.",
        "-- Every damaging move's class in today's games, by Gen 3 move index: \"p\" physical,",
        "-- \"s\" special. The Move Split option (src/move_split.lua) reads it.",
        "return {",
    ]
    for idx in sorted(rows):
        out.append(f"  [{idx}] = \"{rows[idx]}\",")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} moves ({len(rows) - ours} the cart's, {ours} this mod's)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
